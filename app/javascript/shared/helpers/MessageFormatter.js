import mila from 'markdown-it-link-attributes';
import mentionPlugin from './markdownIt/link';
import MarkdownIt from 'markdown-it';

const setImageHeight = inlineToken => {
  const imgSrc = inlineToken.attrGet('src');
  if (!imgSrc) return;
  const url = new URL(imgSrc);
  const height = url.searchParams.get('cw_image_height');
  if (!height) return;
  inlineToken.attrSet('style', `height: ${height};`);
};

const processInlineToken = blockToken => {
  blockToken.children.forEach(inlineToken => {
    if (inlineToken.type === 'image') {
      setImageHeight(inlineToken);
    }
  });
};

const imgResizeManager = md => {
  // Custom rule for image resize in markdown
  // If the image url has a query param cw_image_height, then add a style attribute to the image
  md.core.ruler.after('inline', 'add-image-height', state => {
    state.tokens.forEach(blockToken => {
      if (blockToken.type === 'inline') {
        processInlineToken(blockToken);
      }
    });
  });
};

const createMarkdownInstance = (linkify = true) => {
  return MarkdownIt({
    html: true,
    xhtmlOut: true,
    breaks: true,
    langPrefix: 'language-',
    linkify,
    typographer: true,
    quotes: '\u201c\u201d\u2018\u2019',
    maxNesting: 20,
  })
    .use(mentionPlugin)
    .use(imgResizeManager)
    .use(mila, {
      attrs: {
        class: 'link',
        rel: 'noreferrer noopener nofollow',
        target: '_blank',
      },
    });
};

const TWITTER_USERNAME_REGEX = /(^|[^@\w])@(\w{1,15})\b/g;
const TWITTER_USERNAME_REPLACEMENT = '$1[@$2](http://twitter.com/$2)';
const TWITTER_HASH_REGEX = /(^|\s)#(\w+)/g;
const TWITTER_HASH_REPLACEMENT = '$1[#$2](https://twitter.com/hashtag/$2)';

const EMAIL_REGEX = /\b[A-Za-z0-9._%+-]+@(?:[A-Za-z0-9-]+\.)+[A-Za-z]{2,}\b/g;
const VN_PHONE_REGEX = /(?:\+84|0)(?:[\s\-.]?\d{2,4}){2,4}\b/g;

class MessageFormatter {
  constructor(
    message,
    isATweet = false,
    isAPrivateNote = false,
    linkify = true,
    maskContactInfo = false,
    mentions = []
  ) {
    this.message = message || '';
    this.isAPrivateNote = isAPrivateNote;
    this.isATweet = isATweet;
    this.linkify = linkify;
    this.maskContactInfo = maskContactInfo;
    this.mentions = mentions;
    this.md = createMarkdownInstance(linkify);
  }

  maskEmail(email) {
    if (!email) return '';
    const parts = email.split('@');
    if (parts.length !== 2) return email;
    const [name, domain] = parts;
    const maskedName = name.length > 2 ? `${name.substring(0, 2)}***` : `*`;
    return `${maskedName}@${domain}`;
  }

  maskPhoneNumber(phone) {
    if (!phone) return '';
    const digitsIndices = [];
    for (let i = 0; i < phone.length; i++) {
      if (/\d/.test(phone[i])) {
        digitsIndices.push(i);
      }
    }

    const numDigits = digitsIndices.length;
    let masked = phone;

    if (numDigits > 5) {
      const indicesToMask = digitsIndices.slice(3, numDigits - 2);
      const chars = phone.split('');
      indicesToMask.forEach(idx => {
        chars[idx] = '*';
      });
      masked = chars.join('');
    } else {
      const indicesToMask = digitsIndices.slice(0, Math.max(0, numDigits - 2));
      const chars = phone.split('');
      indicesToMask.forEach(idx => {
        chars[idx] = '*';
      });
      masked = chars.join('');
    }

    return masked;
  }

  formatMessage() {
    let text = this.message || '';
    if (this.mentions && this.mentions.length > 0) {
      const sortedMentions = [...this.mentions].sort((a, b) => b.pos - a.pos);
      sortedMentions.forEach(mention => {
        const { pos, len, uid } = mention;
        if (pos >= 0 && pos + len <= text.length) {
          const mentionText = text.substring(pos, pos + len);
          const replacement = `<strong class="highlight-link underline cursor-pointer text-n-orange-10 hover:text-n-orange dark:text-n-orange-5 transition-colors" data-type="mention" data-value="${uid}"><u>${mentionText}</u></strong>`;
          text =
            text.substring(0, pos) + replacement + text.substring(pos + len);
        }
      });
    }

    let renderedMessage = this.md.render(text);

    // Replace existing mailto links generated by markdown-it with our custom highlights
    renderedMessage = renderedMessage.replace(
      /<a [^>]*href="mailto:([^"]+)"[^>]*>.*?<\/a>/gi,
      (match, email) => {
        const displayValue = this.maskContactInfo
          ? this.maskEmail(email)
          : email;
        return `<strong class="highlight-link underline cursor-pointer text-n-orange-10 hover:text-n-orange dark:text-n-orange-5 transition-colors" data-type="email" data-value="${email}"><u>${displayValue}</u></strong>`;
      }
    );

    // Also catch plain emails that weren't linkified (fallback)
    renderedMessage = renderedMessage.replace(EMAIL_REGEX, match => {
      // Avoid replacing if it's already inside our custom tag (very simple check)
      if (renderedMessage.includes(`data-value="${match}"`)) return match;
      const displayValue = this.maskContactInfo ? this.maskEmail(match) : match;
      return `<strong class="highlight-link underline cursor-pointer text-n-orange-10 hover:text-n-orange dark:text-n-orange-5 transition-colors" data-type="email" data-value="${match}"><u>${displayValue}</u></strong>`;
    });

    // Highlight phone numbers (usually not linkified by markdown-it)
    renderedMessage = renderedMessage.replace(
      VN_PHONE_REGEX,
      (match, offset, string) => {
        const stringBefore = string.substring(0, offset);

        // Skip if match is inside an HTML tag attribute (e.g., href="...")
        const lastOpenTag = stringBefore.lastIndexOf('<');
        const lastCloseTag = stringBefore.lastIndexOf('>');
        if (lastOpenTag > lastCloseTag) return match;

        // Skip if match is inside an existing <a> tag text content
        const openATags = (stringBefore.match(/<a\b/gi) || []).length;
        const closeATags = (stringBefore.match(/<\/a>/gi) || []).length;
        if (openATags > closeATags) return match;

        // Skip if match appears to be part of a plain URL
        if (stringBefore.match(/https?:\/\/[^\s<"']*$/i)) return match;

        const displayValue = this.maskContactInfo
          ? this.maskPhoneNumber(match)
          : match;
        return `<strong class="highlight-link underline cursor-pointer text-n-orange-10 hover:text-n-orange dark:text-n-orange-5 transition-colors" data-type="phone" data-value="${match}"><u>${displayValue}</u></strong>`;
      }
    );

    if (this.isATweet && !this.isAPrivateNote) {
      renderedMessage = renderedMessage.replace(
        TWITTER_USERNAME_REGEX,
        TWITTER_USERNAME_REPLACEMENT
      );
      renderedMessage = renderedMessage.replace(
        TWITTER_HASH_REGEX,
        TWITTER_HASH_REPLACEMENT
      );
    }
    return renderedMessage;
  }

  get formattedMessage() {
    return this.formatMessage();
  }

  get plainText() {
    const strippedOutHtml = new DOMParser().parseFromString(
      this.formattedMessage,
      'text/html'
    );
    return strippedOutHtml.body.textContent || '';
  }
}

export default MessageFormatter;
